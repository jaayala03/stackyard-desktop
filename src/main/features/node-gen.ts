// Generators for the files a Node project needs on DDEV. Port of the second half of stackyard/nodeproj.py.
import type { NodePlan, NodeService } from '../../shared/node'

export const GENERATED_MARK = '# Generated by Stackyard'

/** Arguments of `ddev config` for the plan. `node` overrides the detected Node version. */
export function ddevConfigArgs(plan: NodePlan, node?: string): string[] {
  const args = ['--project-type=generic', '--webserver-type=generic', '--docroot=', `--nodejs-version=${node || plan.node}`]
  args.push(plan.database ? `--database=${plan.database}` : '--omit-containers=db')
  if (plan.yarnOrPnpm) args.push('--corepack-enable')
  return args
}

export const ddevConfigFlags = (plan: NodePlan, node?: string): string => ddevConfigArgs(plan, node).join(' ')

/** Flags for a Node project whose services could not be detected (empty folder, explicit Node type). */
export function fallbackConfigFlags(node: string): string {
  return `--project-type=generic --webserver-type=generic --docroot= --nodejs-version=${node} --omit-containers=db`
}

export function serviceUrl(name: string, tld: string, port: number, scheme: 'https' | 'http' = 'https'): string {
  const base = scheme === 'https' ? 443 : 80
  return `${scheme}://${name}.${tld}` + (port === base ? '' : `:${port}`)
}

export function svcUrl(name: string, tld: string, s: NodeService, scheme: 'https' | 'http' = 'https'): string {
  return s.publicPort ? serviceUrl(name, tld, s.publicPort, scheme) : ''
}

const yamlStr = (value: string): string => JSON.stringify(value) // JSON strings are valid YAML strings
const workdir = (dir: string): string => '/var/www/html' + (dir === '.' ? '' : `/${dir}`)

/** .ddev/config.stackyard.yaml: daemons and exposed ports of every service. */
export function ddevYaml(plan: NodePlan): string {
  const lines = [
    GENERATED_MARK + ' for this Node project. It is merged with config.yaml.',
    '# Edit it freely, or let Stackyard regenerate it (Node tab → Apply).',
    ''
  ]
  if (plan.puppeteer) {
    lines.push(
      'webimage_extra_packages: [chromium, fonts-noto-color-emoji]',
      'web_environment:',
      '  - PUPPETEER_SKIP_DOWNLOAD=true',
      '  - PUPPETEER_EXECUTABLE_PATH=/usr/bin/chromium',
      ''
    )
  }
  lines.push('web_extra_daemons:')
  for (const s of plan.services) {
    const cmd =
      s.kind === 'vite'
        ? `npx vite --config /var/www/html/.ddev/vite.${s.name}.ddev.config.mjs --port ${s.port} --strictPort`
        : (s.command ?? '')
    lines.push(`  - name: ${s.name}`, `    command: ${yamlStr(cmd)}`, `    directory: ${workdir(s.dir)}`)
  }
  lines.push('', 'web_extra_exposed_ports:')
  // the primary service goes first: DDEV uses the first exposed port as the project URL
  const exposed = plan.services.filter((s) => s.kind !== 'worker').sort((a, b) => Number(b.primary) - Number(a.primary))
  for (const s of exposed) {
    lines.push(`  - name: ${s.name}`, `    container_port: ${s.port}`, `    http_port: ${s.httpPort}`, `    https_port: ${s.httpsPort}`)
  }
  lines.push('', 'hooks:', '  post-start:', '    - exec: "bash /var/www/html/.ddev/stackyard-node-prepare.sh"', '')
  return lines.join('\n')
}

/**
 * Runs in the web container after start: installs missing dependencies, rebuilds native modules
 * built on another system (e.g. node_modules copied from Windows), then restarts the daemons.
 */
export function prepareScript(plan: NodePlan): string {
  const out = [
    '#!/bin/bash',
    GENERATED_MARK + ': prepares the Node dependencies in the container.',
    '# --force reinstalls the dependencies of every service.',
    'set -u',
    'changed=0',
    'force="${1:-}"'
  ]
  const seen = new Set<string>()
  for (const s of plan.services) {
    if (seen.has(s.dir)) continue
    seen.add(s.dir)
    const install = { npm: 'npm install --no-audit --no-fund', yarn: 'yarn install', pnpm: 'pnpm install' }[s.pm]
    const rebuild = { npm: 'npm rebuild', yarn: 'npm rebuild', pnpm: 'pnpm rebuild' }[s.pm]
    out.push(
      `cd ${workdir(s.dir)} || exit 0`,
      'marker=node_modules/.stackyard-linux',
      'if [ ! -d node_modules ] || [ "$force" = --force ]; then',
      `  echo 'Stackyard: installing dependencies in ${s.dir}'; ${install} && touch "$marker"; changed=1`,
      'elif [ ! -f "$marker" ]; then',
      `  echo 'Stackyard: rebuilding native modules in ${s.dir} for Linux'; ${rebuild} && touch "$marker"; changed=1`,
      'elif [ package.json -nt "$marker" ]; then',
      `  echo 'Stackyard: package.json changed in ${s.dir}, updating'; ${install} && touch "$marker"; changed=1`,
      'fi'
    )
    // npm 11 skips install scripts not listed in allowScripts: make sure every native module loads
    for (const mod of s.native) {
      out.push(
        `node -e "require('${mod}')" >/dev/null 2>&1 || ` +
          `{ echo 'Stackyard: building native module ${mod}'; npm rebuild ${mod} >/dev/null 2>&1; changed=1; }`
      )
    }
  }
  out.push(`if [ "$changed" = 1 ]; then sudo supervisorctl restart 'webextradaemons:*' >/dev/null 2>&1 || true; fi`, '')
  return out.join('\n')
}

/** .ddev/vite.<service>.ddev.config.mjs: runs the project's Vite config through DDEV without modifying it. */
export function viteWrapper(s: NodeService, plan: NodePlan, tld: string): string {
  // the wrapper lives in .ddev/, so the project's config is one level up
  const relConfig = '../' + (s.dir === '.' ? '' : s.dir + '/') + (s.viteConfig ?? '')
  const proto = plan.scheme === 'https' ? 'wss' : 'ws'
  return `// Generated by Stackyard: runs the project's Vite config through DDEV without modifying it.
import base from '${relConfig}'

export default async (env) => {
  const config = (typeof base === 'function' ? await base(env) : await base) || {}
  return {
    ...config,
    server: {
      ...(config.server || {}),
      host: '0.0.0.0',
      port: ${s.port},
      strictPort: true,
      allowedHosts: ['.${tld}', 'localhost'],
      hmr: { protocol: '${proto}', host: process.env.DDEV_HOSTNAME, clientPort: ${s.publicPort} },
    },
  }
}
`
}
